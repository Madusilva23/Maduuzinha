// ELEMENTOS DA PÁGINA

const container = document.getElementById("teamContainer");
const pesquisa = document.getElementById("search");
const modal = document.getElementById("teamModal");

// CRIAR CARTÕES DAS EQUIPES

function mostrarEquipes(lista = equipes) {

    container.innerHTML = "";

    lista.forEach((equipe, index) => {

        const card = document.createElement("article");
        card.className = "team-card";

        card.style.setProperty("--team-color", equipe.cores[0]);
        card.style.animationDelay = `${index * 70}ms`;

        card.innerHTML = `
            <h3>${equipe.nome}</h3>

            <p>
                ${equipe.pais}<br>
                ${equipe.pilotos.map(p => p.nome).join(" • ")}
            </p>

            <div class="team-colors">
                ${equipe.cores.map(cor =>
                    `<i style="background:${cor}"></i>`
                ).join("")}
            </div>

            <span class="team-open">
                CONHECER HISTÓRIA <span>→</span>
            </span>
        `;

        card.addEventListener("click", () => abrirEquipe(equipe));

        container.appendChild(card);
    });

    if (lista.length === 0) {
        container.innerHTML =
            "<p>Nenhuma equipe encontrada.</p>";
    }
}

// ABRIR HISTÓRIA E PILOTOS

function abrirEquipe(equipe) {

    const conteudo = document.getElementById("modalBody");

    document.getElementById("modalTitle").textContent =
        equipe.nome;

    document.getElementById("modalHeader").style.background =
        equipe.cores[0];

    document.getElementById("modalContent").style.setProperty(
        "--team-color",
        equipe.cores[0]
    );

    conteudo.innerHTML = `
        <h3>🏁 História da equipe</h3>

        <p>${equipe.historia}</p>

        <h3>🎨 Identidade visual</h3>

        <p>
            As cores que representam a equipe são:
            ${equipe.cores.join(", ")}.
        </p>

        <div class="team-colors">
            ${equipe.cores.map(cor =>
                `<i style="background:${cor}"></i>`
            ).join("")}
        </div>

        <h3>🏎️ História dos pilotos</h3>

        ${equipe.pilotos.map(piloto => `
            <div class="modal-pilot">
                <h4>
                    #${piloto.numero} — ${piloto.nome}
                </h4>

                <p>${piloto.historia}</p>
            </div>
        `).join("")}

        ${equipe.substitutos ? `
            <h3>🔄 Pilotos substitutos</h3>

            ${equipe.substitutos.map(nome => `
                <div class="modal-pilot">
                    <p>${nome}</p>
                </div>
            `).join("")}
        ` : ""}
    `;

    modal.classList.add("active");
    document.body.style.overflow = "hidden";
}

// FECHAR JANELA

function fecharEquipe() {
    modal.classList.remove("active");
    document.body.style.overflow = "";
}

// PESQUISAR EQUIPES E PILOTOS

pesquisa.addEventListener("input", () => {

    const termo = pesquisa.value.toLowerCase();

    const resultado = equipes.filter(equipe => {

        const nomeEquipe = equipe.nome.toLowerCase();

        const nomesPilotos = equipe.pilotos
            .map(p => p.nome.toLowerCase())
            .join(" ");

        return nomeEquipe.includes(termo) ||
               nomesPilotos.includes(termo);
    });

    mostrarEquipes(resultado);
});

// LISTA DE TODOS OS PILOTOS

function mostrarPilotos() {

    const lista = document.getElementById("driverList");

    lista.innerHTML = "";

    equipes.forEach(equipe => {

        equipe.pilotos.forEach(piloto => {

            const item = document.createElement("div");
            item.className = "driver-item";

            item.innerHTML = `
                <div>
                    <strong>${piloto.nome}</strong>
                    <small>${equipe.nome}</small>
                </div>

                <span class="driver-number">
                    #${piloto.numero}
                </span>
            `;

            lista.appendChild(item);
        });
    });
}

// MENU PARA CELULAR

function toggleMenu() {

    document.getElementById("menu")
        .classList.toggle("open");
}

document.querySelectorAll("#menu a").forEach(link => {
    link.addEventListener("click", () => {
        document.getElementById("menu").classList.remove("open");
    });
});

// FECHAR CLICANDO FORA DA JANELA

modal.addEventListener("click", event => {
    if (event.target === modal) {
        fecharEquipe();
    }
});

document.addEventListener("keydown", event => {
    if (event.key === "Escape") {
        fecharEquipe();
    }
});

// INICIALIZAÇÃO

mostrarEquipes();
mostrarPilotos();
